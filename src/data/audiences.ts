/** Quy đổi recs (chuỗi gợi ý) → index item thật trong data, chịu sai khác nhỏ. */
export function resolveRecs(aud: AudiencePath, data: PipelineStep[]): Record<string, number[]> {
  const out: Record<string, number[]> = {};
  data.forEach((step) => {
    step.categories.forEach((cat) => {
      const rec = aud.recs[cat.id];
      if (!rec) return;
      const keys = (Array.isArray(rec) ? rec : [rec]).map((r) => r.toLowerCase().trim());
      const idxs: number[] = [];
      keys.forEach((k) => {
        const found = cat.items.findIndex((i) => i.en.toLowerCase().includes(k));
        if (found >= 0 && !idxs.includes(found)) idxs.push(found);
      });
      if (idxs.length) out[cat.id] = idxs;
    });
  });
  return out;
}
